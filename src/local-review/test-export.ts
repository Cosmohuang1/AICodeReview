import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { TestScenario, TestAction, Target } from './types.js';

function loc(target: Target): string {
  switch (target.by) {
    case 'role':
      return 'page.getByRole(' + JSON.stringify(target.value) +
        ' as Parameters<typeof page.getByRole>[0]' +
        (target.name ? ', { name: ' + JSON.stringify(target.name) + ' }' : '') + ')';
    case 'label': return 'page.getByLabel(' + JSON.stringify(target.value) + ')';
    case 'text': return 'page.getByText(' + JSON.stringify(target.value) + ')';
    case 'testId': return 'page.getByTestId(' + JSON.stringify(target.value) + ')';
  }
}

function step(action: TestAction): string {
  switch (action.type) {
    case 'goto': return '  await page.goto(url(' + JSON.stringify(action.path) + '));';
    case 'assertURL': return '  await expect(page).toHaveURL(url(' + JSON.stringify(action.path) + '));';
    case 'assertVisible': return '  await expect(' + loc(action.target) + ').toBeVisible();';
    case 'click':
    case 'fill': throw new Error('Interactive actions cannot be exported without manual design review.');
  }
}

export function generatedTestSource(scenario: TestScenario, defaultBaseURL: string): string {
  if (scenario.expectationSource === 'smoke') throw new Error('Skip smoke-only scenarios when exporting regression tests.');
  if (!scenario.actions.length) throw new Error('Empty scenario');
  const allowedBase = new URL(defaultBaseURL);
  if (!['localhost', '127.0.0.1', '[::1]'].includes(allowedBase.hostname)) {
    throw new Error('Generated test defaults must be local-only');
  }
  if (scenario.actions.some(a => a.type === 'click' || a.type === 'fill')) {
    throw new Error('Interactive tests require manual authoring.');
  }
  if (!scenario.actions.some(a => a.type === 'assertURL' || a.type === 'assertVisible')) {
    throw new Error('A generated regression test must include an explicit assertion.');
  }
  const steps = scenario.actions.map(step).join('\n');
  return [
    '// Generated by AICodeReview. Review the expected behavior before promoting this test.',
    '// Source: ' + scenario.expectationSource + '. AI proposed expectations are NOT verified requirements.',
    "import { test, expect } from '@playwright/test';",
    '',
    'const baseURL = process.env.AI_REVIEW_BASE_URL ?? ' + JSON.stringify(allowedBase.origin) + ';',
    'const url = (route: string) => new URL(route, baseURL).href;',
    '',
    'test(' + JSON.stringify(scenario.id) + ', async ({ page }) => {',
    steps,
    '});',
    ''
  ].join('\n');
}

/** Safe, opted-in export. Never silently edits the target project's tests/ folder. */
export function exportPlaywrightTests(root: string, scenarios: TestScenario[], baseURL: string): {
  saved: string[]; skipped: string[];
} {
  const saved: string[] = [], skipped: string[] = [];
  const directory = path.join(root, '.ai-review', 'generated-tests');
  for (const scenario of scenarios) {
    try {
      const source = generatedTestSource(scenario, baseURL);
      const short = scenario.id.replace(/[^a-z0-9_-]/gi, '-').slice(0, 48);
      const hash = createHash('sha256').update(scenario.id).digest('hex').slice(0, 8);
      const filename = path.join(directory, short + '-' + hash + '.spec.ts');
      mkdirSync(directory, { recursive: true });
      writeFileSync(filename, source, { encoding: 'utf8', flag: 'wx' });
      saved.push(filename);
    } catch (error) {
      skipped.push(scenario.id + ': ' + (error instanceof Error ? error.message : String(error)));
    }
  }
  return { saved, skipped };
}
